<?php

namespace App\Models\Master;

use App\Traits\AuditTrailTrait;
use App\Traits\FilterableSearchableTrait;
use App\Traits\FiscalYearScopedTrait;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

class Vendor extends Model
{
    use HasFactory, SoftDeletes, FilterableSearchableTrait, AuditTrailTrait, FiscalYearScopedTrait;

    protected $table = 'vendors';

    protected $fillable = ['code', 'name', 'type', 'vendor_category_id', 'npwp', 'address', 'contact_person', 'contact_person_title', 'additional_contacts', 'phone', 'email', 'bank_name', 'bank_account_number', 'bank_account_holder', 'tax_id', 'fiscal_year_id', 'is_active', 'created_by', 'updated_by', 'deleted_by'];

    protected $casts = [
        'is_active' => 'boolean',
    ];

    protected static function booted(): void
    {
        static::creating(function (Vendor $vendor) {
            // Vendor Code is strictly auto-generated by the backend generator service
            if (empty($vendor->code)) {
                $vendor->code = app(\App\Services\Master\VendorCodeGeneratorService::class)->generate();
            }

            // Default entity type if not specified
            if (empty($vendor->type)) {
                $vendor->type = 'company';
            }
        });

        static::updating(function (Vendor $vendor) {
            // Vendor Code is strictly read-only after creation; protect from modification
            if ($vendor->isDirty('code') && $vendor->getOriginal('code')) {
                $vendor->code = $vendor->getOriginal('code');
            }
        });
    }

    public function tax()
    {
        return $this->belongsTo(\App\Models\Master\Tax::class, 'tax_id');
    }

    public function fiscalYear()
    {
        return $this->belongsTo(\App\Models\Master\FiscalYear::class, 'fiscal_year_id');
    }

    public function category()
    {
        return $this->belongsTo(VendorCategory::class, 'vendor_category_id');
    }

}
